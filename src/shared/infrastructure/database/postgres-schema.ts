/**
 * PostgreSQL schema for Hexa. IDs are UUID, timestamps TIMESTAMPTZ, JSON
 * columns JSONB and boolean flags BOOLEAN. The application generates UUIDs;
 * no extension is required.
 *
 * Every foreign key is deferrable so the one-time SQLite migration can load
 * self-referencing tables (menu groups, quote versions) inside a transaction.
 */
export const POSTGRES_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS users (
  id                    UUID PRIMARY KEY,
  email                 TEXT NOT NULL UNIQUE,
  name                  TEXT NOT NULL,
  created_at            TIMESTAMPTZ NOT NULL,
  password_hash         TEXT,
  status                TEXT NOT NULL DEFAULT 'active',
  failed_login_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until          TIMESTAMPTZ,
  password_changed_at   TIMESTAMPTZ,
  must_change_password  BOOLEAN NOT NULL DEFAULT FALSE,
  last_login_at         TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS roles (
  id          UUID PRIMARY KEY,
  name        TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  permissions JSONB NOT NULL DEFAULT '[]'::jsonb,
  built_in    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS roles_name_lower_idx ON roles (LOWER(name));

CREATE TABLE IF NOT EXISTS user_roles (
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  role_id UUID NOT NULL REFERENCES roles(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS user_permissions (
  user_id        UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  permission_key TEXT NOT NULL,
  granted_at     TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (user_id, permission_key)
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
  id         UUID PRIMARY KEY,
  user_id    UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS password_history (
  id            UUID PRIMARY KEY,
  user_id       UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  password_hash TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS api_keys (
  id           UUID PRIMARY KEY,
  user_id      UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  name         TEXT NOT NULL,
  prefix       TEXT NOT NULL,
  key_hash     TEXT NOT NULL UNIQUE,
  scopes       JSONB,
  expires_at   TIMESTAMPTZ,
  last_used_at TIMESTAMPTZ,
  revoked_at   TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS patients (
  id                     UUID PRIMARY KEY,
  rut                    TEXT NOT NULL UNIQUE,
  nombres                TEXT NOT NULL,
  apellido_paterno       TEXT NOT NULL,
  apellido_materno       TEXT NOT NULL,
  fecha_nacimiento       DATE NOT NULL,
  sexo                   TEXT NOT NULL,
  email                  TEXT,
  telefono               TEXT,
  direccion_region       TEXT,
  direccion_comuna       TEXT,
  direccion_calle        TEXT,
  direccion_numero       TEXT,
  direccion_departamento TEXT,
  prevision_tipo         TEXT,
  prevision_tramo        TEXT,
  prevision_plan         TEXT,
  contacto_nombre        TEXT,
  contacto_telefono      TEXT,
  contacto_parentesco    TEXT,
  notas                  TEXT,
  numero_historia        TEXT,
  created_at             TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS patients_numero_historia_idx ON patients (numero_historia) WHERE numero_historia IS NOT NULL;
ALTER TABLE patients ADD COLUMN IF NOT EXISTS prevision_convenio TEXT;

CREATE TABLE IF NOT EXISTS settings (
  key        TEXT PRIMARY KEY,
  value      JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS settings_audit (
  id         UUID PRIMARY KEY,
  at         TIMESTAMPTZ NOT NULL,
  actor_id   UUID NOT NULL,
  actor_type TEXT NOT NULL,
  changes    JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_settings_audit_at ON settings_audit (at DESC);

CREATE TABLE IF NOT EXISTS bootstrap_state (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS menu_items (
  id                  UUID PRIMARY KEY,
  seq                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
  parent_id           UUID REFERENCES menu_items(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  kind                TEXT NOT NULL DEFAULT 'item',
  label               TEXT,
  icon                TEXT,
  route_key           TEXT,
  external_url        TEXT,
  position            INTEGER NOT NULL,
  required_permission TEXT,
  enabled             BOOLEAN NOT NULL DEFAULT TRUE,
  created_at          TIMESTAMPTZ NOT NULL,
  updated_at          TIMESTAMPTZ NOT NULL,
  created_by          UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  updated_by          UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE
);
CREATE INDEX IF NOT EXISTS idx_menu_items_parent ON menu_items (parent_id, position);
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS seq BIGINT GENERATED BY DEFAULT AS IDENTITY;

CREATE TABLE IF NOT EXISTS clinic_assets (
  id         UUID PRIMARY KEY,
  variant    TEXT NOT NULL,
  mime       TEXT NOT NULL,
  width      INTEGER NOT NULL,
  height     INTEGER NOT NULL,
  bytes      BYTEA NOT NULL,
  size       INTEGER NOT NULL,
  hash       TEXT NOT NULL,
  version    INTEGER NOT NULL,
  active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL,
  created_by UUID REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE
);
CREATE INDEX IF NOT EXISTS idx_assets_variant ON clinic_assets (variant, active, version DESC);

CREATE TABLE IF NOT EXISTS clinical_records (
  id                     UUID PRIMARY KEY,
  patient_id             UUID NOT NULL UNIQUE REFERENCES patients(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  categoria              TEXT NOT NULL,
  embarazada             BOOLEAN NOT NULL DEFAULT FALSE,
  motivo_consulta        TEXT,
  enfermedad_actual      TEXT,
  antecedentes           JSONB NOT NULL DEFAULT '{}'::jsonb,
  signos_vitales         JSONB NOT NULL DEFAULT '{}'::jsonb,
  examen_estomatognatico JSONB NOT NULL DEFAULT '{}'::jsonb,
  indicadores            JSONB NOT NULL DEFAULT '{}'::jsonb,
  status                 TEXT NOT NULL DEFAULT 'borrador',
  created_by             UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  updated_by             UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  created_at             TIMESTAMPTZ NOT NULL,
  updated_at             TIMESTAMPTZ NOT NULL,
  finalized_at           TIMESTAMPTZ,
  finalized_by           UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE IF NOT EXISTS clinical_findings (
  id         UUID PRIMARY KEY,
  record_id  UUID NOT NULL REFERENCES clinical_records(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  tooth      INTEGER NOT NULL,
  surfaces   JSONB NOT NULL DEFAULT '[]'::jsonb,
  symbol     TEXT NOT NULL,
  state      TEXT NOT NULL,
  recesion   INTEGER,
  movilidad  INTEGER,
  note       TEXT,
  created_by UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  created_at TIMESTAMPTZ NOT NULL,
  voided_at  TIMESTAMPTZ,
  voided_by  UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE
);
CREATE INDEX IF NOT EXISTS idx_clinical_findings_record ON clinical_findings (record_id, tooth);

CREATE TABLE IF NOT EXISTS clinical_events (
  id         UUID PRIMARY KEY,
  patient_id UUID NOT NULL,
  record_id  UUID NOT NULL REFERENCES clinical_records(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  actor_id   UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  action     TEXT NOT NULL,
  summary    TEXT,
  payload    JSONB,
  created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_clinical_events_record ON clinical_events (record_id, created_at);

CREATE TABLE IF NOT EXISTS uco_procedures (
  id         UUID PRIMARY KEY,
  code       TEXT NOT NULL UNIQUE,
  chapter    TEXT NOT NULL,
  name       TEXT NOT NULL,
  units      DOUBLE PRECISION NOT NULL,
  active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_by UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  updated_by UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_uco_code ON uco_procedures (code);

CREATE TABLE IF NOT EXISTS quotes (
  id                  UUID PRIMARY KEY,
  folio               TEXT NOT NULL UNIQUE,
  patient_id          UUID NOT NULL REFERENCES patients(id) ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE,
  patient_name        TEXT NOT NULL,
  patient_rut         TEXT NOT NULL,
  patient_email       TEXT,
  status              TEXT NOT NULL,
  valid_until         TIMESTAMPTZ,
  notes               TEXT,
  subtotal            INTEGER NOT NULL,
  discount_total      INTEGER NOT NULL,
  total               INTEGER NOT NULL,
  version             INTEGER NOT NULL DEFAULT 1,
  replaces_quote_id   UUID REFERENCES quotes(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  created_by          UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  created_by_name     TEXT NOT NULL,
  created_at          TIMESTAMPTZ NOT NULL,
  updated_by          UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  updated_by_name     TEXT NOT NULL,
  updated_at          TIMESTAMPTZ NOT NULL,
  sanctioned_by       UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  sanctioned_by_name  TEXT,
  sanctioned_at       TIMESTAMPTZ,
  deleted_at          TIMESTAMPTZ,
  deleted_by          UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  deleted_by_name     TEXT
);
CREATE INDEX IF NOT EXISTS idx_quotes_patient ON quotes (patient_id);
CREATE INDEX IF NOT EXISTS idx_quotes_status ON quotes (status);
CREATE INDEX IF NOT EXISTS idx_quotes_deleted ON quotes (deleted_at);
CREATE INDEX IF NOT EXISTS idx_quotes_folio ON quotes (folio);

CREATE TABLE IF NOT EXISTS quote_items (
  id                     UUID PRIMARY KEY,
  quote_id               UUID NOT NULL REFERENCES quotes(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  position               INTEGER NOT NULL,
  uco_code               TEXT REFERENCES uco_procedures(code) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  description            TEXT NOT NULL,
  pieza_dental           TEXT,
  quantity               INTEGER NOT NULL,
  unit_price             INTEGER NOT NULL,
  discount_percent       INTEGER NOT NULL DEFAULT 0,
  subtotal               INTEGER NOT NULL,
  discount_amount        INTEGER NOT NULL DEFAULT 0,
  net_amount             INTEGER NOT NULL,
  status                 TEXT NOT NULL,
  status_changed_by      UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  status_changed_by_name TEXT,
  status_changed_at      TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_quote_items_quote ON quote_items (quote_id, position);

CREATE TABLE IF NOT EXISTS quote_versions (
  id            UUID PRIMARY KEY,
  quote_id      UUID NOT NULL REFERENCES quotes(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  version       INTEGER NOT NULL,
  action        TEXT NOT NULL,
  snapshot_json JSONB NOT NULL,
  actor_id      UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  actor_name    TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_quote_versions_quote ON quote_versions (quote_id, version);

CREATE TABLE IF NOT EXISTS quote_counters (
  year        INTEGER PRIMARY KEY,
  last_number INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS caro_conversations (
  id         UUID PRIMARY KEY,
  user_id    UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  title      TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  deleted_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_caro_conversations_user ON caro_conversations (user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS caro_messages (
  id              UUID PRIMARY KEY,
  conversation_id UUID NOT NULL REFERENCES caro_conversations(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  role            TEXT NOT NULL,
  content         TEXT NOT NULL DEFAULT '',
  tool_calls      JSONB NOT NULL DEFAULT '[]'::jsonb,
  citations       JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at      TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_caro_messages_conversation ON caro_messages (conversation_id, created_at);

CREATE TABLE IF NOT EXISTS caro_approvals (
  id              UUID PRIMARY KEY,
  conversation_id UUID NOT NULL REFERENCES caro_conversations(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  message_id      UUID NOT NULL REFERENCES caro_messages(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  tool            TEXT NOT NULL,
  title           TEXT NOT NULL,
  summary         TEXT NOT NULL,
  parameters      JSONB NOT NULL DEFAULT '[]'::jsonb,
  arguments       JSONB NOT NULL,
  status          TEXT NOT NULL DEFAULT 'pending',
  expires_at      TIMESTAMPTZ NOT NULL,
  decided_at      TIMESTAMPTZ,
  decided_by      UUID,
  created_at      TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_caro_approvals_pending ON caro_approvals (conversation_id, status, expires_at);

CREATE TABLE IF NOT EXISTS activity_log (
  id            UUID PRIMARY KEY,
  at            TIMESTAMPTZ NOT NULL,
  actor_id      UUID,
  actor_type    TEXT NOT NULL,
  actor_label   TEXT,
  action        TEXT NOT NULL,
  module        TEXT NOT NULL,
  subject_type  TEXT,
  subject_id    TEXT,
  subject_label TEXT,
  outcome       TEXT NOT NULL,
  status_code   INTEGER,
  method        TEXT NOT NULL,
  path          TEXT NOT NULL,
  route         TEXT,
  ip            TEXT,
  user_agent    TEXT,
  metadata      JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_activity_at ON activity_log (at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_actor ON activity_log (actor_id, at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_action ON activity_log (action, at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_subject ON activity_log (subject_type, subject_id, at DESC);

CREATE TABLE IF NOT EXISTS appointments (
  id                  UUID PRIMARY KEY,
  patient_id          UUID NOT NULL REFERENCES patients(id) ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE,
  professional_id     UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE,
  starts_at           TIMESTAMPTZ NOT NULL,
  ends_at             TIMESTAMPTZ NOT NULL,
  status              TEXT NOT NULL DEFAULT 'scheduled',
  reason              TEXT,
  notes               TEXT,
  location            TEXT,
  ics_sequence        INTEGER NOT NULL DEFAULT 0,
  created_by          UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  updated_by          UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  created_at          TIMESTAMPTZ NOT NULL,
  updated_at          TIMESTAMPTZ NOT NULL,
  cancelled_at        TIMESTAMPTZ,
  cancelled_by        UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE
);
CREATE INDEX IF NOT EXISTS idx_appointments_starts ON appointments (starts_at);
CREATE INDEX IF NOT EXISTS idx_appointments_professional ON appointments (professional_id, starts_at);
CREATE INDEX IF NOT EXISTS idx_appointments_patient ON appointments (patient_id, starts_at);
CREATE INDEX IF NOT EXISTS idx_appointments_status ON appointments (status, starts_at);

CREATE TABLE IF NOT EXISTS agenda_email_outbox (
  id                  UUID PRIMARY KEY,
  appointment_id      UUID NOT NULL REFERENCES appointments(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  event_type          TEXT NOT NULL,
  recipient_kind      TEXT NOT NULL,
  recipient_email     TEXT NOT NULL,
  subject             TEXT NOT NULL,
  html                TEXT NOT NULL,
  text                TEXT NOT NULL,
  ics                 TEXT NOT NULL,
  status              TEXT NOT NULL DEFAULT 'pending',
  attempts            INTEGER NOT NULL DEFAULT 0,
  next_attempt_at     TIMESTAMPTZ NOT NULL,
  last_error          TEXT,
  created_at          TIMESTAMPTZ NOT NULL,
  sent_at             TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_agenda_email_pending ON agenda_email_outbox (status, next_attempt_at);

CREATE TABLE IF NOT EXISTS agenda_reasons (
  id         UUID PRIMARY KEY,
  name       TEXT NOT NULL,
  created_by UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  updated_by UUID REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS agenda_reasons_name_lower_idx ON agenda_reasons (LOWER(name));

CREATE TABLE IF NOT EXISTS schema_migrations (
  version    TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO schema_migrations (version) VALUES ('2026-10-postgresql')
ON CONFLICT (version) DO NOTHING;
`;
